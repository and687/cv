create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  title text not null unique,
  description text not null,
  technology text not null default '',
  url text,
  sort_order integer not null default 0,
  constraint projects_url_https check (url is null or url like 'https://%')
);

create table if not exists public.experiences (
  id bigint generated by default as identity primary key,
  date text not null,
  title text not null,
  organization text not null default '',
  details text[] not null default '{}',
  sort_order integer not null default 0,
  constraint experiences_entry_unique unique (date, title, organization)
);

create table if not exists public.skills (
  id bigint generated by default as identity primary key,
  name text not null unique,
  sort_order integer not null default 0
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 1 and 100),
  email text not null check (char_length(email) <= 254 and email ~* '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'),
  subject text not null check (char_length(btrim(subject)) between 1 and 150),
  message text not null check (char_length(btrim(message)) between 1 and 5000),
  created_at timestamptz not null default now()
);

alter table public.projects enable row level security;
alter table public.experiences enable row level security;
alter table public.skills enable row level security;
alter table public.messages enable row level security;

drop policy if exists "Public can read projects" on public.projects;
create policy "Public can read projects" on public.projects
  for select to anon, authenticated using (true);

drop policy if exists "Public can read experiences" on public.experiences;
create policy "Public can read experiences" on public.experiences
  for select to anon, authenticated using (true);

drop policy if exists "Public can read skills" on public.skills;
create policy "Public can read skills" on public.skills
  for select to anon, authenticated using (true);

drop policy if exists "Public can submit messages" on public.messages;
create policy "Public can submit messages" on public.messages
  for insert to anon, authenticated
  with check (
    char_length(btrim(name)) between 1 and 100
    and char_length(email) <= 254
    and email ~* '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
    and char_length(btrim(subject)) between 1 and 150
    and char_length(btrim(message)) between 1 and 5000
  );

revoke all on public.projects, public.experiences, public.skills from public, anon, authenticated;
grant select on public.projects, public.experiences, public.skills to anon, authenticated;
revoke all on public.messages from public, anon, authenticated;
grant insert (name, email, subject, message) on public.messages to anon, authenticated;
revoke all on sequence public.messages_id_seq from public, anon, authenticated;
grant usage, select on sequence public.messages_id_seq to anon, authenticated;

